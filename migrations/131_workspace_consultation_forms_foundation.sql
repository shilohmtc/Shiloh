-- Workspace consultation forms foundation.
--
-- This migration creates versioned form templates and reusable question sections,
-- maps the first two forms to canonical service IDs, and creates assignment/status
-- metadata. It deliberately creates no public form route, sends no WhatsApp
-- message, stores no plaintext access token, and backfills no client answers.

CREATE TABLE IF NOT EXISTS consultation_form_sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_key TEXT NOT NULL UNIQUE CHECK (BTRIM(section_key) <> ''),
  title TEXT NOT NULL CHECK (BTRIM(title) <> ''),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS consultation_form_section_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id BIGINT NOT NULL REFERENCES consultation_form_sections(id) ON DELETE RESTRICT,
  version_number INTEGER NOT NULL CHECK (version_number > 0),
  definition JSONB NOT NULL CHECK (jsonb_typeof(definition) = 'object'),
  source_label TEXT NOT NULL CHECK (BTRIM(source_label) <> ''),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (section_id, version_number)
);

CREATE TABLE IF NOT EXISTS consultation_form_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_key TEXT NOT NULL UNIQUE CHECK (BTRIM(template_key) <> ''),
  title TEXT NOT NULL CHECK (BTRIM(title) <> ''),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS consultation_form_template_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id BIGINT NOT NULL REFERENCES consultation_form_templates(id) ON DELETE RESTRICT,
  version_number INTEGER NOT NULL CHECK (version_number > 0),
  consent_text TEXT NOT NULL CHECK (BTRIM(consent_text) <> ''),
  settings JSONB NOT NULL DEFAULT '{"signature_required":true}'::jsonb
    CHECK (jsonb_typeof(settings) = 'object'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (template_id, version_number)
);

CREATE TABLE IF NOT EXISTS consultation_form_template_sections (
  template_version_id BIGINT NOT NULL REFERENCES consultation_form_template_versions(id) ON DELETE RESTRICT,
  section_version_id BIGINT NOT NULL REFERENCES consultation_form_section_versions(id) ON DELETE RESTRICT,
  position INTEGER NOT NULL CHECK (position > 0),
  PRIMARY KEY (template_version_id, section_version_id),
  UNIQUE (template_version_id, position)
);

CREATE TABLE IF NOT EXISTS consultation_form_service_mappings (
  service_id BIGINT NOT NULL REFERENCES services(id) ON DELETE RESTRICT,
  template_version_id BIGINT NOT NULL REFERENCES consultation_form_template_versions(id) ON DELETE RESTRICT,
  required BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (service_id, template_version_id)
);

CREATE TABLE IF NOT EXISTS consultation_form_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
  template_version_id BIGINT NOT NULL REFERENCES consultation_form_template_versions(id) ON DELETE RESTRICT,
  client_id BIGINT REFERENCES clients(id) ON DELETE RESTRICT,
  crm_v2_client_id BIGINT REFERENCES crm_v2_clients(id) ON DELETE RESTRICT,
  status TEXT NOT NULL DEFAULT 'not_sent'
    CHECK (status IN ('not_sent', 'sent', 'opened', 'completed', 'needs_review')),
  access_token_hash TEXT CHECK (access_token_hash IS NULL OR access_token_hash ~ '^[0-9a-f]{64}$'),
  access_expires_at TIMESTAMPTZ,
  sent_at TIMESTAMPTZ,
  opened_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  needs_review_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT consultation_form_assignment_one_client CHECK (
    (client_id IS NOT NULL AND crm_v2_client_id IS NULL)
    OR (client_id IS NULL AND crm_v2_client_id IS NOT NULL)
  ),
  CONSTRAINT consultation_form_assignment_token_pair CHECK (
    (access_token_hash IS NULL AND access_expires_at IS NULL)
    OR (access_token_hash IS NOT NULL AND access_expires_at IS NOT NULL)
  ),
  UNIQUE (appointment_id, template_version_id)
);

CREATE INDEX IF NOT EXISTS idx_consultation_form_assignments_status
  ON consultation_form_assignments(status, appointment_id);
CREATE INDEX IF NOT EXISTS idx_consultation_form_assignments_client
  ON consultation_form_assignments(client_id) WHERE client_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_consultation_form_assignments_crm_v2_client
  ON consultation_form_assignments(crm_v2_client_id) WHERE crm_v2_client_id IS NOT NULL;

-- Practitioner notes are intentionally separate from the client questionnaire.
-- The client form surface must never read this table.
CREATE TABLE IF NOT EXISTS consultation_form_practitioner_notes (
  assignment_id BIGINT PRIMARY KEY REFERENCES consultation_form_assignments(id) ON DELETE RESTRICT,
  note TEXT NOT NULL CHECK (CHAR_LENGTH(note) <= 10000),
  author_admin_id BIGINT NOT NULL REFERENCES staff_admin_accounts(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

