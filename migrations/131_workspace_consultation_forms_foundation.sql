-- Narrow initial Workspace access: senior clinic principals and the shared
-- Reception operator may view the Forms control centre. Practitioner-scoped
-- access to client submissions will be introduced with the secure client form
-- surface so health information is not broadened before that boundary exists.
UPDATE staff_admin_accounts
   SET permissions = COALESCE(permissions, '{}'::jsonb) || '{"forms:view":true}'::jsonb,
       updated_at = NOW()
 WHERE active=TRUE
   AND business_role IN ('owner','business_admin','booking_operator')
   AND COALESCE((permissions ->> 'forms:view')::boolean, FALSE) IS NOT TRUE;
