-- Resolve service names exactly once during the controlled migration, then persist
-- canonical service IDs. Runtime form selection never matches free-text treatment names.
DO $forms$
DECLARE
  v_swedish_service_id BIGINT;
  v_hot_stone_service_id BIGINT;
  v_swedish_template_version_id BIGINT;
  v_hot_stone_template_version_id BIGINT;
BEGIN
  SELECT id INTO STRICT v_swedish_service_id
    FROM services
   WHERE status='active' AND name='Full Body Swedish';

  SELECT id INTO STRICT v_hot_stone_service_id
    FROM services
   WHERE status='active' AND name='Hot Stone Massage';

  SELECT tv.id INTO STRICT v_swedish_template_version_id
    FROM consultation_form_template_versions tv
    JOIN consultation_form_templates t ON t.id=tv.template_id
   WHERE t.template_key='swedish_massage_consultation' AND tv.version_number=1;

  SELECT tv.id INTO STRICT v_hot_stone_template_version_id
    FROM consultation_form_template_versions tv
    JOIN consultation_form_templates t ON t.id=tv.template_id
   WHERE t.template_key='hot_stone_massage_consultation' AND tv.version_number=1;

  INSERT INTO consultation_form_service_mappings(service_id, template_version_id, required)
  VALUES
    (v_swedish_service_id, v_swedish_template_version_id, TRUE),
    (v_hot_stone_service_id, v_hot_stone_template_version_id, TRUE)
  ON CONFLICT (service_id, template_version_id) DO NOTHING;
END
