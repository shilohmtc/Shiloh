  UPDATE staff_admin_accounts
     SET permissions = COALESCE(permissions, '{}'::jsonb)
                       || '{"problem_reports:manage":true}'::jsonb,
         updated_at = NOW()
   WHERE active = TRUE
     AND LOWER(BTRIM(display_name)) IN ('jean-pierre','jean pierre','jp')
     AND business_role = 'business_admin';
END $$;

COMMENT ON TABLE problem_reports IS
  'Authenticated client and staff problem reports. Only the explicitly permissioned JP account may list or manage the private inbox.';
