-- Shiloh booking deposit policy.
-- Payment truth remains separate from appointment/attendance truth.
-- This policy is prospective from the production migration timestamp.

CREATE TABLE IF NOT EXISTS booking_deposit_policies (
  policy_key TEXT PRIMARY KEY,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  deposit_basis_points INTEGER NOT NULL CHECK (deposit_basis_points BETWEEN 0 AND 10000),
  full_release_notice_hours INTEGER NOT NULL CHECK (full_release_notice_hours > 0),
  partial_notice_hours INTEGER NOT NULL CHECK (partial_notice_hours >= 0 AND partial_notice_hours < full_release_notice_hours),
  partial_retention_basis_points INTEGER NOT NULL CHECK (partial_retention_basis_points BETWEEN 0 AND 10000),
  late_retention_basis_points INTEGER NOT NULL CHECK (late_retention_basis_points BETWEEN 0 AND 10000),
  no_show_retention_basis_points INTEGER NOT NULL CHECK (no_show_retention_basis_points BETWEEN 0 AND 10000),
  exempt_staff_display_name TEXT NOT NULL CHECK (BTRIM(exempt_staff_display_name) <> ''),
  exempt_staff_business_role TEXT NOT NULL CHECK (BTRIM(exempt_staff_business_role) <> ''),
  activated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

