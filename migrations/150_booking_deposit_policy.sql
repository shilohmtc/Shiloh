ON CONFLICT (policy_key) DO NOTHING;

CREATE TABLE IF NOT EXISTS booking_payment_requirements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_account_id BIGINT NOT NULL UNIQUE REFERENCES booking_payment_accounts(id) ON DELETE RESTRICT,
  requirement_type TEXT NOT NULL DEFAULT 'booking_deposit' CHECK (requirement_type='booking_deposit'),
  policy_key TEXT NOT NULL REFERENCES booking_deposit_policies(policy_key) ON DELETE RESTRICT,
  percentage_basis_points INTEGER NOT NULL CHECK (percentage_basis_points BETWEEN 0 AND 10000),
  eligible_amount_base NUMERIC(12,2) NOT NULL CHECK (eligible_amount_base >= 0),
  required_amount NUMERIC(12,2) NOT NULL CHECK (required_amount >= 0),
  full_release_notice_hours INTEGER NOT NULL CHECK (full_release_notice_hours > 0),
  partial_notice_hours INTEGER NOT NULL CHECK (partial_notice_hours >= 0),
  partial_retention_basis_points INTEGER NOT NULL CHECK (partial_retention_basis_points BETWEEN 0 AND 10000),
  late_retention_basis_points INTEGER NOT NULL CHECK (late_retention_basis_points BETWEEN 0 AND 10000),
  no_show_retention_basis_points INTEGER NOT NULL CHECK (no_show_retention_basis_points BETWEEN 0 AND 10000),
  exempt_reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS booking_payment_requirement_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requirement_id BIGINT NOT NULL REFERENCES booking_payment_requirements(id) ON DELETE RESTRICT,
  appointment_id BIGINT NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
  eligible_amount NUMERIC(12,2) NOT NULL CHECK (eligible_amount >= 0),
  required_amount NUMERIC(12,2) NOT NULL CHECK (required_amount >= 0),
  exempt_reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(requirement_id,appointment_id)
);

