CREATE TABLE IF NOT EXISTS booking_deposit_dispositions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requirement_id BIGINT NOT NULL REFERENCES booking_payment_requirements(id) ON DELETE RESTRICT,
  appointment_id BIGINT NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
  event_kind TEXT NOT NULL CHECK (event_kind IN ('rescheduled','cancelled','no_show')),
  event_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  original_starts_at TIMESTAMPTZ NOT NULL,
  notice_hours NUMERIC(12,2),
  retention_basis_points INTEGER NOT NULL CHECK (retention_basis_points BETWEEN 0 AND 10000),
  appointment_deposit_share NUMERIC(12,2) NOT NULL CHECK (appointment_deposit_share >= 0),
  policy_retention_amount NUMERIC(12,2) NOT NULL CHECK (policy_retention_amount >= 0),
  retained_amount NUMERIC(12,2) NOT NULL CHECK (retained_amount >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_booking_deposit_dispositions_requirement
  ON booking_deposit_dispositions(requirement_id,created_at);

