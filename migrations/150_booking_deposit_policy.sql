CREATE OR REPLACE FUNCTION record_booking_deposit_policy_disposition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  requirement_row booking_payment_requirements%ROWTYPE;
  item_row booking_payment_requirement_items%ROWTYPE;
  account_id BIGINT;
  event_name TEXT;
  event_time TIMESTAMPTZ := clock_timestamp();
  hours_notice NUMERIC(12,2);
  retention_bps INTEGER;
  retention_cap NUMERIC(12,2);
  net_received NUMERIC(12,2);
  already_retained NUMERIC(12,2);
  available_to_retain NUMERIC(12,2);
  actual_retained NUMERIC(12,2);
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status AND NEW.status='no_show' THEN
    event_name := 'no_show';
  ELSIF NEW.status IS DISTINCT FROM OLD.status AND NEW.status='cancelled' THEN
    event_name := 'cancelled';
  ELSIF NEW.starts_at IS DISTINCT FROM OLD.starts_at THEN
    event_name := 'rescheduled';
  ELSE
    RETURN NEW;
  END IF;

  SELECT req, item
    INTO requirement_row, item_row
    FROM booking_payment_requirement_items item
    JOIN booking_payment_requirements req ON req.id=item.requirement_id
   WHERE item.appointment_id=NEW.id
   ORDER BY req.id DESC
   LIMIT 1;

  IF NOT FOUND OR item_row.required_amount <= 0 THEN
    RETURN NEW;
  END IF;

  SELECT req.payment_account_id
    INTO account_id
    FROM booking_payment_requirements req
   WHERE req.id=requirement_row.id;

  hours_notice := ROUND((EXTRACT(EPOCH FROM (OLD.starts_at-event_time))/3600.0)::numeric,2);

  IF event_name='no_show' THEN
    retention_bps := requirement_row.no_show_retention_basis_points;
  ELSIF hours_notice >= requirement_row.full_release_notice_hours THEN
    retention_bps := 0;
  ELSIF hours_notice >= requirement_row.partial_notice_hours THEN
    retention_bps := requirement_row.partial_retention_basis_points;
  ELSE
    retention_bps := requirement_row.late_retention_basis_points;
  END IF;

  retention_cap := ROUND(item_row.required_amount * retention_bps / 10000.0,2);

  SELECT COALESCE(SUM(CASE WHEN entry_type='payment' THEN amount ELSE -amount END),0)
    INTO net_received
    FROM payment_ledger_entries
   WHERE payment_account_id=account_id;

  SELECT COALESCE(SUM(retained_amount),0)
    INTO already_retained
    FROM booking_deposit_dispositions
   WHERE requirement_id=requirement_row.id;

  available_to_retain := GREATEST(0,net_received-already_retained);
  actual_retained := LEAST(retention_cap,available_to_retain);

  INSERT INTO booking_deposit_dispositions(
    requirement_id,appointment_id,event_kind,event_at,original_starts_at,notice_hours,
    retention_basis_points,appointment_deposit_share,policy_retention_amount,retained_amount
  ) VALUES(
    requirement_row.id,NEW.id,event_name,event_time,OLD.starts_at,hours_notice,
    retention_bps,item_row.required_amount,retention_cap,actual_retained
  );

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_booking_deposit_policy_disposition ON appointments;
CREATE TRIGGER trg_booking_deposit_policy_disposition
AFTER UPDATE OF starts_at,status ON appointments
FOR EACH ROW
WHEN (
  OLD.starts_at IS DISTINCT FROM NEW.starts_at
  OR (OLD.status IS DISTINCT FROM NEW.status AND NEW.status IN ('cancelled','no_show'))
)
EXECUTE FUNCTION record_booking_deposit_policy_disposition();

COMMENT ON TABLE booking_payment_requirements IS
  'Prospective booking-deposit obligations. Payment evidence remains in the immutable payment ledger.';
COMMENT ON TABLE booking_deposit_dispositions IS
  'Policy calculations for reschedule/cancellation/no-show. These rows never issue a refund or mutate payment evidence.';
