-- Prior settlement evidence is not a new receipt, goodwill, or a price change.
CREATE TABLE booking_prior_payment_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_payment_account_id BIGINT NOT NULL REFERENCES booking_payment_accounts(id) ON DELETE RESTRICT,
  appointment_id BIGINT NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
  crm_v2_client_id BIGINT NOT NULL REFERENCES crm_v2_clients(id) ON DELETE RESTRICT,
  entry_type TEXT NOT NULL CHECK (entry_type IN ('apply','undo')),
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  signed_amount NUMERIC(12,2) GENERATED ALWAYS AS (CASE WHEN entry_type='apply' THEN amount ELSE -amount END) STORED,
  source_payment_ledger_entry_id BIGINT REFERENCES payment_ledger_entries(id) ON DELETE RESTRICT,
  source_payment_account_id BIGINT REFERENCES booking_payment_accounts(id) ON DELETE RESTRICT,
  correction_target_id BIGINT UNIQUE REFERENCES booking_prior_payment_entries(id) ON DELETE RESTRICT,
  payment_date DATE NOT NULL,
  reference TEXT NOT NULL CHECK (CHAR_LENGTH(TRIM(reference)) BETWEEN 1 AND 120),
  reason TEXT NOT NULL CHECK (CHAR_LENGTH(TRIM(reason)) BETWEEN 1 AND 240),
  actor_admin_id BIGINT NOT NULL REFERENCES staff_admin_accounts(id) ON DELETE RESTRICT,
  operation_id TEXT NOT NULL UNIQUE,
  request_fingerprint TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((source_payment_ledger_entry_id IS NULL) = (source_payment_account_id IS NULL)),
  CHECK (source_payment_account_id IS NULL OR source_payment_account_id <> booking_payment_account_id),
  CHECK ((entry_type='undo') = (correction_target_id IS NOT NULL))
);
CREATE INDEX ON booking_prior_payment_entries(booking_payment_account_id);
CREATE INDEX ON booking_prior_payment_entries(source_payment_account_id);
CREATE INDEX ON booking_prior_payment_entries(crm_v2_client_id,payment_date,LOWER(TRIM(reference)));
ALTER TABLE payment_requests ADD COLUMN prior_payment_closed_by_entry_id BIGINT REFERENCES booking_prior_payment_entries(id) ON DELETE RESTRICT;
CREATE FUNCTION protect_booking_prior_payment_evidence() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Prior payment evidence is immutable; record a reversal'; END;
$$;
CREATE TRIGGER booking_prior_payment_immutable BEFORE UPDATE OR DELETE ON booking_prior_payment_entries
  FOR EACH ROW EXECUTE FUNCTION protect_booking_prior_payment_evidence();

CREATE OR REPLACE VIEW booking_prior_payment_totals AS
  SELECT account_id,SUM(incoming) AS incoming,SUM(outgoing) AS outgoing FROM (
    SELECT booking_payment_account_id AS account_id,signed_amount AS incoming,0::numeric AS outgoing FROM booking_prior_payment_entries
    UNION ALL SELECT source_payment_account_id,0::numeric,signed_amount FROM booking_prior_payment_entries WHERE source_payment_account_id IS NOT NULL
  ) movement GROUP BY account_id;

-- Last-line protection for imported/admin SQL evidence, in addition to API locks.
CREATE FUNCTION validate_booking_prior_payment_evidence() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE source_row payment_ledger_entries%ROWTYPE; original booking_prior_payment_entries%ROWTYPE;
BEGIN
  IF NEW.entry_type='undo' THEN
    SELECT * INTO original FROM booking_prior_payment_entries WHERE id=NEW.correction_target_id;
    IF original.entry_type<>'apply' OR NEW.amount<>original.amount
      OR NEW.booking_payment_account_id<>original.booking_payment_account_id
      OR NEW.appointment_id<>original.appointment_id OR NEW.crm_v2_client_id<>original.crm_v2_client_id
      OR NEW.source_payment_ledger_entry_id IS DISTINCT FROM original.source_payment_ledger_entry_id
      OR NEW.source_payment_account_id IS DISTINCT FROM original.source_payment_account_id
      OR NEW.payment_date<>original.payment_date OR NEW.reference<>original.reference THEN
      RAISE EXCEPTION 'Prior payment reversal must exactly match original settlement evidence';
    END IF;
  ELSIF NEW.source_payment_ledger_entry_id IS NOT NULL THEN
    SELECT * INTO source_row FROM payment_ledger_entries WHERE id=NEW.source_payment_ledger_entry_id;
    IF source_row.entry_type<>'payment' OR source_row.payment_account_id<>NEW.source_payment_account_id
      OR (SELECT COALESCE(SUM(signed_amount),0) FROM booking_prior_payment_entries
        WHERE source_payment_ledger_entry_id=NEW.source_payment_ledger_entry_id)>source_row.amount THEN
      RAISE EXCEPTION 'Prior payment allocation exceeds original receipt evidence';
    END IF;
  ELSE
    IF EXISTS(SELECT 1 FROM booking_prior_payment_entries e WHERE e.id<>NEW.id AND e.entry_type='apply'
      AND e.crm_v2_client_id=NEW.crm_v2_client_id AND LOWER(TRIM(e.reference))=LOWER(TRIM(NEW.reference))
      AND NOT EXISTS(SELECT 1 FROM booking_prior_payment_entries undo WHERE undo.correction_target_id=e.id)) THEN
      RAISE EXCEPTION 'Prior payment reference is already allocated';
    END IF;
  END IF;
  RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER booking_prior_payment_evidence_valid AFTER INSERT ON booking_prior_payment_entries
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_booking_prior_payment_evidence();

COMMENT ON TABLE booking_prior_payment_entries IS 'Audited historical settlement and existing receipt allocations. Excluded from cash receipts, cash-up and new rewards; never changes treatment price.';
