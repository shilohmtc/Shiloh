'use strict';
const { PGlite } = require('@electric-sql/pglite');
const fs = require('node:fs');
const crypto = require('node:crypto');
const { createWorkspaceWhatsAppStore } = require('../../src/services/workspaceWhatsAppStore');
const { createWorkspaceWhatsAppAuth } = require('../../src/services/workspaceWhatsAppAuth');
const { createStaffBrowserSessionService, issueStaffBrowserSession } = require('../../src/services/staffBrowserSession');
async function harness(t) {
  let pg, realPool = null;
  const syntheticUrl = process.env.WORKSPACE_WHATSAPP_SYNTHETIC_DATABASE_URL;
  if (syntheticUrl) {
    const url = new URL(syntheticUrl);
    if (!['127.0.0.1','localhost'].includes(url.hostname) || url.pathname !== '/wa_synthetic') throw Error('Only local wa_synthetic database is allowed');
    const {Pool}=require('pg');
    const schema='wa_synthetic_'+crypto.randomBytes(8).toString('hex');
    const control=new Pool({connectionString:syntheticUrl});
    await control.query(`CREATE SCHEMA ${schema}`);
    realPool=new Pool({connectionString:syntheticUrl,max:8,options:`-c search_path=${schema},public`});
    pg={exec:sql=>realPool.query(sql),query:(sql,args)=>realPool.query(sql,args)};
    t.after(async()=>{await realPool.end();await control.query(`DROP SCHEMA ${schema} CASCADE`);await control.end();});
  } else {
    pg = new PGlite(); t.after(() => pg.close());
  }
  await pg.exec(`CREATE TABLE staff(id BIGINT PRIMARY KEY,status TEXT);
    CREATE TABLE staff_admin_accounts(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,staff_id BIGINT REFERENCES staff(id),
      display_name TEXT,normalized_whatsapp TEXT,active BOOLEAN NOT NULL DEFAULT TRUE,role TEXT,business_role TEXT,
      calendar_scope TEXT,service_scope TEXT,updated_at TIMESTAMPTZ DEFAULT NOW(),permissions JSONB NOT NULL DEFAULT '{}');`);
  for (const file of ['078_staff_browser_sessions.sql','081_provider_independent_staff_auth.sql',
    '111_staff_passkey_auth_v1.sql','112_staff_passkey_auth_v1_production_schema_correction.sql',
    '113_staff_whatsapp_passkey_bootstrap_v1.sql','119_workspace_passkey_device_labels.sql',
    '156_staff_discoverable_passkey_handoff.sql','190_staff_detail_signin.sql']) await pg.exec(fs.readFileSync(`migrations/${file}`,'utf8'));
  await pg.exec(fs.readFileSync('docs/proposed-migrations/workspace_whatsapp_auth.sql','utf8'));
  const current = new Date();
  let queue = Promise.resolve();
  const query = async (sql,args) => { const r=await pg.query(sql,args); return { rows:r.rows,rowCount:r.rowCount ?? r.affectedRows ?? r.rows.length }; };
  const db = { query, async connect() {
    if(realPool)return realPool.connect();
    let release; const previous=queue; queue=new Promise(r=>{release=r;}); await previous;
    return { query,release };
  } };
  for (const id of [1,2]) await query(`INSERT INTO staff_admin_accounts(id,display_name,normalized_whatsapp,role,business_role,calendar_scope,service_scope,permissions)
    VALUES($1,$2,$3,'owner','owner','all_business','all_services',$4::jsonb)`,
  [id,`Synthetic Staff ${id}`,`2782000000${id}`,JSON.stringify({'appointment:view':true,'staff_auth:reset':id===2})]);
  const owner = (await query('SELECT *,active AS admin_active FROM staff_admin_accounts WHERE id=2')).rows[0];
  const old = (await query('SELECT *,active AS admin_active FROM staff_admin_accounts WHERE id=1')).rows[0];
  const operatorSession=await issueStaffBrowserSession({client:db,admin:owner,current,authMethod:'passkey'});
  const priorSession=await issueStaffBrowserSession({client:db,admin:old,current,authMethod:'passkey'});
  const env={SHILOH_STAFF_PASSKEY_AUTH_ENABLED:'true',SHILOH_CALENDAR_PUBLIC_ORIGIN:'https://staff.example.test'};
  const sent=[];
  const delivery={configured:()=>true,readiness:async()=>({ready:true,codeTtlSeconds:300}),deliver:async input=>{sent.push(input);return{ok:true,providerMessageId:'wamid.synthetic'};}};
  const store=createWorkspaceWhatsAppStore({db});
  const service=createWorkspaceWhatsAppAuth({enabled:true,store,delivery,hmacKey:Buffer.alloc(32,7),env});
  const sessions=createStaffBrowserSessionService({db});
  const context={browserToken:'B'.repeat(43),network:'192.0.2.0/24',mobile:'27820000001',purpose:'signin'};
  async function code(purpose='signin') {
    const input={...context,purpose};
    if(purpose!=='signin') {
      const r=await service.requestSetup(input); input.setupIntent=r.intent;
      const approval=await service.approveSetup({intent:r.intent,sessionId:operatorSession.sessionId,identityConfirmed:true});
      if(!approval.ok)throw Error('synthetic approval failed');
    }
    const r=await service.begin(input);
    return service.verify({...input,request:r.request,code:sent.at(-1).code});
  }
  return {pg,db,service,sessions,context,operatorSession,priorSession,sent,code,env};
}
module.exports={harness};
