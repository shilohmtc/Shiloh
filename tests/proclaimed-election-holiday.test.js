const test = require('node:test');
const assert = require('node:assert/strict');
const { PGlite } = require('@electric-sql/pglite');
const { publicHolidayCalendarSql } = require('../src/config/publicHolidayCalendar');
const { getClinicWindowForDate } = require('../src/services/clinicHours');
const { checkAssistantBookingHours } = require('../src/services/assistantBookingHours');
const { listAvailableSlots } = require('../src/services/availabilityService');
const { createWorkspaceClinicHoursHolidayGuard } = require('../src/services/workspaceClinicHoursHolidayGuard');
const { createWorkspaceClinicHoursService } = require('../src/services/workspaceClinicHours');
const { listHolidayDecisions } = require('../src/services/workspaceHolidayAttention');
const { createSchedulingEngine } = require('../src/services/schedulingEngine');
const { listCanonicalPublicHolidays } = require('../src/services/calendarReadOnlyUx');
const { processAdminHolidayHoursMessage } = require('../src/services/adminHolidayHours');
const { pool } = require('../src/db/pool');

test('proclaimed election holiday is coherent across SQL readers without changing stored decisions or appointments', async () => {
  const pg = new PGlite();
  const db = { query: async (sql, params) => { const r = await pg.query(sql, params); return { ...r, rowCount: r.rows.length }; } };
  const original = pool.query; pool.query = db.query;
  try {
    await pg.exec(`
      CREATE TABLE locations(id bigint, name text, status text, timezone text);
      INSERT INTO locations VALUES(1,'Synthetic','active','Africa/Johannesburg');
      CREATE TABLE public_holidays(holiday_date date,country_code text,name text,observed boolean);
      CREATE TABLE location_hours_exceptions(id bigint GENERATED ALWAYS AS IDENTITY,location_id bigint,exception_date date,exception_type text,starts_local time,ends_local time,reason text);
      CREATE TABLE location_working_hours(location_id bigint,day_of_week int,active boolean,starts_local time,ends_local time);
      INSERT INTO location_working_hours VALUES(1,3,true,'08:00','17:00');
      CREATE TABLE staff(id bigint,display_name text,status text,scheduling_type text);
      INSERT INTO staff VALUES(1,'Synthetic','active','regular');
      CREATE TABLE services(id bigint,name text,status text,duration_minutes int,processing_time_minutes int,extra_time_minutes int);
      INSERT INTO services VALUES(1,'Synthetic treatment','active',60,15,15);
      CREATE TABLE staff_services(staff_id bigint,service_id bigint); INSERT INTO staff_services VALUES(1,1);
      CREATE TABLE staff_working_hours(staff_id bigint,location_id bigint,day_of_week int,active boolean,starts_local time,ends_local time);
      CREATE TABLE staff_recurring_day_closures(staff_id bigint,location_id bigint,day_of_week int);
      CREATE TABLE staff_schedule_exceptions(staff_id bigint,location_id bigint,exception_date date,exception_type text,starts_local time,ends_local time);
      CREATE TABLE appointment_staff(staff_id bigint,appointment_id bigint);
      CREATE TABLE appointments(id bigint,status text,starts_at timestamptz,ends_at timestamptz);
      CREATE TABLE calendar_blocks(staff_id bigint,starts_at timestamptz,ends_at timestamptz);
      CREATE TABLE appointment_booking_approvals(appointment_id bigint,proposed_staff_ids bigint[],status text,proposal_expires_at timestamptz,proposed_starts_at timestamptz,proposed_ends_at timestamptz);
      CREATE TABLE location_assistant_hours_exceptions(location_id bigint,exception_date date,exception_type text,starts_local time,ends_local time);
      CREATE TABLE location_assistant_booking_hours(location_id bigint,day_of_week int,active boolean,starts_local time,ends_local time);
      INSERT INTO location_assistant_booking_hours VALUES(1,3,true,'08:00','17:00');
    `);
    const date = '2026-11-04';
    assert.equal((await listCanonicalPublicHolidays({ startKey: date, endKey: '2026-11-05' }))[0].name, 'Local Government Election Day');
    // Synthetic authenticated WhatsApp readback: no outbound message or mutation.
    pool.query = async (sql, params) => sql.includes('FROM staff_admin_accounts') ? { rows: [{ id: 1, permissions: { 'schedule:manage': true } }] } : db.query(sql, params);
    const readback = await processAdminHolidayHoursMessage('+27820000000', 'holiday hours 2026-11-04');
    assert.match(readback.reply, /Local Government Election Day/);
    pool.query = db.query;
    const args = { staffId: 1, serviceId: 1, locationId: 1, date };
    const window = () => getClinicWindowForDate({ db, locationId: 1, date });
    const guard = createWorkspaceClinicHoursHolidayGuard({ db });
    assert.equal((await guard.requireLoadedZaPublicHoliday(date)).holidayName, 'Local Government Election Day');
    await assert.rejects(guard.requireLoadedZaPublicHoliday('2027-11-04'), /loaded South African/);
    await assert.rejects(guard.requireLoadedZaPublicHoliday('2026-11-05'), /loaded South African/);
    assert.equal((await window()).reason, 'holiday_unconfigured');
    assert.equal((await listAvailableSlots(args)).slots.length, 0);
    const attention = await listHolidayDecisions({ db, now: new Date('2026-11-02T22:30Z') });
    assert.deepEqual(attention.map(x => x.exceptionDate), [date]);
    const modelDb = { query: async (sql, params) => {
      if (sql.includes('workspaceClinicHours:principal')) return { rows: [{ id: 1, admin_active: true, permissions: { 'schedule:manage': true } }] };
      if (sql.includes('workspaceClinicHours:holidayRows')) return db.query(sql, params);
      return { rows: [] };
    } };
    const service = createWorkspaceClinicHoursService({ db: modelDb, locationResolver: async () => ({ id: 1, name: 'Synthetic', timezone: 'Africa/Johannesburg' }) });
    const model = () => service.buildModel({ adminId: 1, now: new Date('2026-11-03T08:00Z') });
    assert.equal((await model()).holidays.find(x => x.exceptionDate === date).holidayName, 'Local Government Election Day');
    const engine = createSchedulingEngine({ query: async (sql, params) => {
      if (sql.includes('SchedulingTimeline:public_holidays')) return db.query(sql, params);
      if (sql.includes('SchedulingTimeline:staff */')) return { rows: [{ id: 1, display_name: 'Synthetic', scheduling_type: 'regular', calendar_scope: 'all_business', business_role: 'employee_practitioner' }] };
      return { rows: [] };
    } });
    const timeline = await engine.listTimeline({ from: '2026-11-04T06:00Z', to: '2026-11-04T16:00Z', viewer: { calendarScope: 'all_business' }, staffIds: [1] });
    assert.ok(timeline.closures.some(x => new Date(x.date).toISOString().slice(0, 10) === date));
    await pg.exec("INSERT INTO location_hours_exceptions(location_id,exception_date,exception_type,starts_local,ends_local) VALUES(1,'2026-11-04','open','10:00','14:00')");
    assert.equal((await window()).covered, true);
    assert.ok((await listAvailableSlots(args)).slots.length > 0);
    assert.equal((await model()).holidays.find(x => x.exceptionDate === date).clinicExceptionType, 'open');
    assert.equal((await listHolidayDecisions({ db, now: new Date('2026-11-03T08:00Z') })).length, 0);
    await pg.exec("INSERT INTO location_assistant_hours_exceptions VALUES(1,'2026-11-04','closed',NULL,NULL)");
    assert.equal((await checkAssistantBookingHours({ db, locationId: 1, startsAt: '2026-11-04T08:00Z', endsAt: '2026-11-04T09:30Z' })).covered, false);
    await pg.exec("INSERT INTO appointments VALUES(1,'confirmed','2026-11-04T09:00Z','2026-11-04T10:00Z'); INSERT INTO appointment_staff VALUES(1,1); INSERT INTO calendar_blocks VALUES(1,'2026-11-04T06:00Z','2026-11-04T16:00Z')");
    const before = await db.query('SELECT * FROM appointments');
    assert.equal((await listAvailableSlots(args)).slots.length, 0);
    await pg.exec("UPDATE location_hours_exceptions SET exception_type='closed',starts_local=NULL,ends_local=NULL");
    assert.equal((await window()).reason, 'date_closed');
    assert.equal((await listAvailableSlots(args)).slots.length, 0);
    assert.deepEqual(await db.query('SELECT * FROM appointments'), before);
    assert.equal((await db.query('SELECT * FROM calendar_blocks')).rows.length, 1);
    assert.equal((await db.query('SELECT * FROM public_holidays')).rows.length, 0);
    await pg.exec("INSERT INTO public_holidays VALUES('2026-11-04','ZA','Stored official name',TRUE)");
    const rows = (await db.query(`SELECT * FROM ${publicHolidayCalendarSql} h WHERE holiday_date=$1::date`, [date])).rows;
    assert.equal(rows.length, 1); assert.equal(rows[0].name, 'Stored official name'); assert.equal(rows[0].observed, true);
    assert.equal((await guard.requireLoadedZaPublicHoliday(date)).holidayName, 'Stored official name');
    assert.equal((await window()).reason, 'date_closed');
    assert.equal((await db.query(`SELECT * FROM ${publicHolidayCalendarSql} h WHERE holiday_date='2027-11-04'`)).rows.length, 0);
  } finally { pool.query = original; await pg.close(); }
});
