'use strict';
const { test, expect } = require('@playwright/test');
const AxeBuilder = require('@axe-core/playwright').default;
const fs = require('node:fs');
for (const width of [1440, 390]) test(`Already attended ${width}: confirm, cancel, stale recovery and accessibility`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  const calls = [];
  let stale = true;
  await page.route('**/calendar/staff-auth/csrf', route => route.fulfill({ json: { csrfToken: 'synthetic-only' } }));
  await page.route('**/calendar/workspace/booking-requests/**', route => {
    calls.push({ url: route.request().url(), body: route.request().postDataJSON(), headers: route.request().headers() });
    if (!stale) return route.fulfill({ json: { ok: true, status: 'approved', outcome: 'completed' } });
    return route.fulfill({ status: 409, json: { code: 'BOOKING_REQUEST_STALE', error: 'This visit or request changed. Refresh Workspace before trying again.' } });
  });
  await page.route('**/calendar/payments/appointments/100/completion-state',route=>route.fulfill({json:{payment:{outstanding:'500.00'},subject:{pricingRevision:'2020-01-01T00:00:00.000Z'},authority:{canCollect:true}}}));
  await page.goto('/iframe.html?id=workspace-already-attended--past-requests&viewMode=story');
  const frame = page.frameLocator('iframe');
  const card = frame.locator('[data-booking-request="100"]');
  const button = card.getByRole('button', { name: 'Already attended', exact: true });
  await expect(button).toBeVisible();
  await expect(frame.locator('[data-booking-request="101"]').getByRole('button', { name: 'Already attended' })).toHaveCount(0);
  await button.click();
  const dialog = frame.getByRole('dialog',{name:'Mark this visit as attended?'});
  await expect(dialog).toContainText('No booking message or deposit request will be sent.');
  await dialog.getByRole('button', { name: 'Keep request' }).click();
  expect(calls).toHaveLength(0);
  await button.click();
  fs.mkdirSync('artifacts/already-attended', { recursive: true });
  await page.screenshot({ path: `artifacts/already-attended/confirmation-${width}.png`, fullPage: true });
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(axe.violations.filter(v => ['serious', 'critical'].includes(v.impact))).toEqual([]);
  expect(await frame.locator('html').evaluate(el => el.scrollWidth <= window.innerWidth)).toBe(true);
  await dialog.getByRole('button', { name: 'Already attended', exact: true }).click();
  const payment=frame.getByRole('dialog',{name:'Complete visit and payment'});
  expect(calls).toHaveLength(0);
  await payment.getByRole('button',{name:'Payment outstanding',exact:true}).click();
  await expect(payment).toContainText('Refresh Workspace');
  expect(calls).toHaveLength(1);
  expect(calls[0].url).toContain('/booking-requests/100/already-attended');
  expect(calls[0].body).toEqual({ expectedRevision: '2020-01-01T00:00:00.000Z', expectedAppointmentRevision: '2020-01-01T00:00:00.000Z', expectedApprovalRevision: '2020-01-01T00:00:00.000Z', paymentDecision:{choice:'outstanding'} });
  expect(calls[0].headers['x-shiloh-csrf-token']).toBe('synthetic-only');
  await payment.getByRole('button',{name:'Close payment window'}).click();
  await expect(button).toBeEnabled();
  await card.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `artifacts/already-attended/card-${width}.png`, fullPage: true });
  stale = false;
  await button.click();
  await dialog.getByRole('button', { name: 'Already attended', exact: true }).click();
  await payment.getByRole('button',{name:'Payment outstanding',exact:true}).click();
  await expect(payment.getByRole('heading',{name:'Visit completed'})).toBeVisible();
  expect(calls).toHaveLength(2);
});
