const test = require('node:test');
const assert = require('node:assert/strict');
const { createGuestFixture } = require('./helpers/calendarGuestBookingFixture');
const { createGuestBookingChangeService, attemptGuestBookingChange } = require('../src/services/guestBookingChanges');
const { createMyShilohPushService } = require('../src/services/myShilohPush');
const { ACTION_BY_KIND } = require('../src/services/customerChangeNotification');
const now = new Date('2030-01-01T00:00:00Z');

async function setup(t) {
  const f = await createGuestFixture(t);
  await f.sql.exec(`ALTER TABLE crm_audit_events ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
    CREATE TABLE customer_change_notifications(audit_event_id BIGINT PRIMARY KEY REFERENCES crm_audit_events(id),
      appointment_id BIGINT REFERENCES appointments(id),change_kind TEXT,status TEXT DEFAULT 'pending',
      attempt_count INT DEFAULT 0,last_error TEXT,suppression_reason TEXT,suppressed_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ DEFAULT NOW(),updated_at TIMESTAMPTZ DEFAULT NOW(),sent_at TIMESTAMPTZ);`);
  return f;
}
async function event(f, kind, { position = 0, action = ACTION_BY_KIND[kind] } = {}) {
  const appointmentId = f.created.appointmentIds[position];
  await f.db.query("UPDATE appointments SET status=$2,updated_at=updated_at+INTERVAL '1 second',notes='Synthetic private clinical note' WHERE id=$1", [appointmentId, kind === 'cancellation' ? 'cancelled' : 'scheduled']);
  const audit = (await f.db.query(`INSERT INTO crm_audit_events(action,entity_type,entity_id,metadata)
    VALUES($1,'appointment',$2,'{"privateDetail":"Synthetic private clinical note","total":"650.00"}') RETURNING id`, [action, appointmentId])).rows[0].id;
  await f.db.query('INSERT INTO customer_change_notifications(audit_event_id,appointment_id,change_kind) VALUES($1,$2,$3)', [audit, appointmentId, kind]);
  return audit;
}
const state = async (f, id) => (await f.db.query('SELECT * FROM customer_change_notifications WHERE audit_event_id=$1', [id])).rows[0];

test('disabled guest change dispatch performs no reads or sends', async () => {
  let reads = 0;
  const db = { query: async () => { reads++; return { rows: [{ ready: false }] }; } };
  assert.deepEqual(await attemptGuestBookingChange(1, { db, enabled: false }), { handled: false });
  assert.equal(reads, 0);
  assert.deepEqual(await attemptGuestBookingChange(1, { db, enabled: true }), { handled: false });
  assert.equal(reads, 1);
  assert.deepEqual(await attemptGuestBookingChange(1, { db }), { handled: false });
  assert.equal(reads, 2, 'the enabled release still checks storage readiness');
});

test('all canonical material changes use an audited organiser notice, preserve other guests, and expose only current messages', async t => {
  const f = await setup(t);
  const wakes = [];
  const service = createGuestBookingChangeService({ db: f.db, now: () => now, wake: async id => { wakes.push(id); return { accepted: 1 }; } });
  const titles = [], ids = [];
  for (const kind of ['time', 'service', 'practitioner', 'price', 'cancellation']) {
    const audit = await event(f, kind);
    const first = await service.attempt(audit);
    assert.equal(first.handled, true);
    assert.equal(first.outcome.sent, true);
    assert.equal(first.outcome.recipientRole, 'organiser');
    assert.equal((await state(f, audit)).status, 'sent');
    assert.equal((await service.attempt(audit)).outcome.reason, 'already_sent');
    ids.push(first.outcome.notificationId);
    const row = (await f.db.query('SELECT * FROM my_shiloh_push_notifications WHERE id=$1', [first.outcome.notificationId])).rows[0];
    assert.equal(Number(row.crm_v2_client_id), 201);
    assert.equal(row.target_path, '/my-shiloh/');
    assert.match(row.body, /Synthetic Guest A/);
    assert.doesNotMatch(row.body, /clinical|650|\/forms|sign.in|payment|refund/);
    titles.push(row.body);
  }
  assert.equal(new Set(ids).size, 5);
  assert.deepEqual(wakes, [201, 201, 201, 201, 201]);
  assert.match(titles[0], /^Appointment time updated/);
  assert.match(titles[1], /^Treatment selection updated/);
  assert.match(titles[2], /^Practitioner updated/);
  assert.match(titles[3], /^Booking details updated/);
  assert.match(titles[4], /^Booking cancelled/);
  assert.deepEqual((await f.db.query('SELECT status FROM appointments ORDER BY id')).rows.map(r => r.status), ['cancelled', 'scheduled', 'scheduled']);
  const visible = await createMyShilohPushService({ db: f.db, env: {}, now: () => now }).listForClient({ crmV2ClientId: 201 });
  assert.deepEqual(visible.notifications.map(n => n.id), [ids.at(-1)]);
  assert.equal(visible.notifications[0].requiresAttention, true);
});

test('unaccepted wakes retry the same obligation; acceptance evidence failure stays uncertain without a second wake', async t => {
  const f = await setup(t);
  const audit = await event(f, 'time');
  let accepted = 0, wakes = 0;
  const service = createGuestBookingChangeService({ db: f.db, now: () => now, wake: async () => { wakes++; return { accepted }; } });
  const first = await service.attempt(audit);
  assert.equal(first.outcome.reason, 'app_wake_unaccepted');
  assert.equal((await state(f, audit)).status, 'pending');
  accepted = 1;
  await f.sql.exec("ALTER TABLE crm_audit_events ADD CONSTRAINT fail_acceptance CHECK(action <> 'customer.booking_update_confirmation_sent')");
  const retry = await service.attempt(audit);
  assert.equal(retry.outcome.reason, 'app_outcome_uncertain');
  assert.equal(retry.outcome.notificationId, first.outcome.notificationId);
  assert.equal((await state(f, audit)).status, 'sending');
  assert.equal((await service.attempt(audit)).outcome.reason, 'provider_outcome_uncertain');
  assert.equal(wakes, 2);
  assert.equal((await f.db.query("SELECT COUNT(*)::int n FROM crm_audit_events WHERE action='booking.guest_change_queued'")).rows[0].n, 1);
});

test('private scope, unrelated source audits and obsolete outcomes never become organiser notices; direct clients retain their original route', async t => {
  const f = await setup(t);
  let wakes = 0;
  const service = createGuestBookingChangeService({ db: f.db, now: () => now, wake: async () => { wakes++; return { accepted: 1 }; } });
  const invalid = await event(f, 'price', { action: 'booking.payment_recorded' });
  assert.equal((await service.attempt(invalid)).outcome.reason, 'guest_change_audit_mismatch');
  const privateAudit = await event(f, 'time');
  await f.db.query("INSERT INTO service_visibility_policies(service_id,visibility_scope,owner_staff_id) VALUES(81,'tenant_private',11)");
  assert.equal((await service.attempt(privateAudit)).outcome.reason, 'guest_booking_recipient_unavailable');
  await f.db.query('DELETE FROM service_visibility_policies');
  const old = await event(f, 'time');
  await f.db.query("UPDATE appointments SET status='completed' WHERE id=$1", [f.created.appointmentIds[0]]);
  assert.equal((await service.attempt(old)).outcome.suppressed, true);
  const direct = await event(f, 'time', { position: 2 });
  assert.deepEqual(await service.attempt(direct), { handled: false });
  assert.equal((await state(f, direct)).status, 'pending');
  assert.equal(wakes, 0);
  assert.equal((await f.db.query("SELECT COUNT(*)::int n FROM my_shiloh_push_notifications WHERE event_key LIKE 'guest-booking:booking_changed:%'")).rows[0].n, 0);
});

test('a lost pre-wake commit response preserves an exact retry; a changed recipient after commit prevents the old wake', async t => {
  const f = await setup(t);
  const audit = await event(f, 'time');
  let lost = false, wakes = 0;
  const db = { ...f.db, connect: async () => {
    const tx = await f.db.connect();
    return { release: (...args) => tx.release(...args), query: async (sql, args) => {
      const result = await tx.query(sql, args);
      if (sql === 'COMMIT' && !lost) { lost = true; throw new Error('Synthetic lost commit'); }
      return result;
    } };
  } };
  const wake = async () => { wakes++; return { accepted: 1 }; };
  await assert.rejects(createGuestBookingChangeService({ db, now: () => now, wake }).attempt(audit), /lost commit/);
  assert.equal(wakes, 0);
  assert.equal((await state(f, audit)).status, 'pending');
  assert.equal((await createGuestBookingChangeService({ db: f.db, now: () => now, wake }).attempt(audit)).outcome.sent, true);
  assert.equal(wakes, 1);
  const moved = await event(f, 'practitioner');
  let changed = false;
  const driftDb = { ...f.db, connect: async () => {
    const tx = await f.db.connect();
    return { release: (...args) => tx.release(...args), query: async (sql, args) => {
      const result = await tx.query(sql, args);
      if (sql === 'COMMIT' && !changed) { changed = true; await f.db.query('UPDATE appointment_group_booking_contacts SET revision=revision+1'); }
      return result;
    } };
  } };
  assert.equal((await createGuestBookingChangeService({ db: driftDb, now: () => now, wake }).attempt(moved)).outcome.reason, 'guest_context_changed');
  assert.equal(wakes, 1);
  assert.equal((await state(f, moved)).status, 'pending');
  assert.deepEqual((await createMyShilohPushService({ db: f.db, env: {}, now: () => now }).listForClient({ crmV2ClientId: 201 })).notifications, []);
});
