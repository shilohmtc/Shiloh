test('passkey enrollment is optional for a valid details session; replacement and revoked enrollment fail', async (t) => {
  const h = await harness(t);
  const signed = await h.attempt();
  const session = await h.sessions.validateSessionToken(signed.sessionToken);
  const start = await h.passkeys.beginRegistration({ session });
  assert.equal(start.ok, true);
  const f = fixture();
  f.challenge = start.options.challenge;
  const finish = await h.passkeys.finishRegistration({
    session,
    response: registrationResponse(f),
  });
  assert.equal(finish.ok, true);
  assert.equal(
    (await h.passkeys.finishRegistration({ session, response: registrationResponse(f) })).code,
    'STAFF_PASSKEY_INVALID',
  );
  assert.equal(
    (await h.sessions.validateSessionToken(signed.sessionToken)).authMethod,
    'staff_details',
  );
  const signIn = await h.passkeys.beginAuthentication();
  f.challenge = signIn.options.challenge;
  const credential = (await h.db.query('SELECT * FROM staff_auth_passkey_credentials')).rows[0];
  const authenticated = await h.passkeys.finishAuthentication({
    response: assertionResponse(f, credential),
  });
  assert.equal(authenticated.ok, true);
  assert.equal(
    (await h.sessions.validateSessionToken(authenticated.sessionToken)).authMethod,
    'passkey',
  );
  const again = await h.attempt();
  Object.assign(session, await h.sessions.validateSessionToken(again.sessionToken));
  assert.equal(
    (await h.passkeys.beginRegistration({ session, mode: 'replace' })).code,
    'STAFF_RECENT_STRONG_AUTH_REQUIRED',
  );
  await h.sessions.revokeSession(session.sessionId, 'logout');
  assert.equal((await h.passkeys.beginRegistration({ session })).code, 'STAFF_AUTH_FORBIDDEN');
});
test('recording details requires current passkey authority, revision and unchanged recorded mobile', async (t) => {
  const h = await harness(t);
  const signed = await issueStaffBrowserSession({
    client: h.db,
    admin: { ...h.owner, admin_active: true },
    current: h.now(),
    authMethod: 'passkey',
  });
  const session = await h.sessions.validateSessionToken(signed.sessionToken);
  const model = await h.setup.read({ session });
  assert.equal(model.ok, true);
  assert.equal(
    (await h.setup.save({ session, input, expectedRevision: 'stale' })).code,
    'STAFF_DETAIL_SETUP_STALE',
  );
  assert.equal(
    (
      await h.setup.save({
        session,
        input: { ...input, mobile: '0820000002' },
        expectedRevision: model.revision,
      })
    ).code,
    'STAFF_DETAIL_SETUP_INVALID',
  );
  assert.equal(
    (
      await h.setup.save({
        session,
        input: { ...input, surname: 'New Surname' },
        expectedRevision: model.revision,
      })
    ).ok,
    true,
  );
  assert.deepEqual(
    (await h.db.query('SELECT permissions FROM staff_admin_accounts')).rows[0].permissions,
    h.owner.permissions,
  );
  const detailSigned = await h.attempt({ ...input, surname: 'New Surname' });
  const detailsSession = await h.sessions.validateSessionToken(detailSigned.sessionToken);
  assert.equal(
    (await h.setup.save({ session: detailsSession, input, expectedRevision: model.revision })).code,
    'STAFF_RECENT_STRONG_AUTH_REQUIRED',
  );
});
