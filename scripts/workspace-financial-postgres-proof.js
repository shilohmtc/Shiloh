const {Client}=require('pg');
const assert=require('node:assert/strict');
const path=require('node:path').resolve(__dirname,'..');
const {RECEIPTS_SQL,TREATMENTS_SQL,BALANCES_SQL,VOUCHERS_SQL,summarizeFinancials}=require(path+'/src/services/workspaceFinancialReports');
const {resolvePeriod}=require(path+'/src/services/workspaceReports');
(async()=>{
 const url=new URL(process.env.FINANCIAL_PROOF_DATABASE_URL || '');
 if (!['localhost','127.0.0.1'].includes(url.hostname) || url.pathname !== '/shiloh_financial_test') throw new Error('Financial SQL proof requires its isolated local test database.');
 const db=new Client({connectionString:url.toString()});
 await db.connect();
 try {
 await db.query('BEGIN');
 await db.query(`
 CREATE TEMPORARY TABLE client_package_entitlements(id bigint,purchased_at timestamptz,purchase_price numeric,payment_method text,payment_status text);
 CREATE TEMPORARY TABLE appointments(id bigint PRIMARY KEY,starts_at timestamptz,status text,total_price numeric,title text);
 CREATE TEMPORARY TABLE appointment_services(appointment_id bigint,position int,service_name_snapshot text);
 CREATE TEMPORARY TABLE appointment_groups(id bigint PRIMARY KEY,final_total numeric,total_price numeric);
 CREATE TEMPORARY TABLE appointment_group_members(group_id bigint,appointment_id bigint,allocated_price numeric);
 CREATE TEMPORARY TABLE booking_payment_accounts(id bigint,appointment_id bigint,appointment_group_id bigint,canonical_amount_due numeric);
 CREATE TEMPORARY TABLE payment_ledger_entries(id bigint,payment_account_id bigint,created_at timestamptz,entry_type text,amount numeric,method text);
 CREATE TEMPORARY TABLE booking_loyalty_allocations(booking_payment_account_id bigint,amount numeric,state text);
 CREATE TEMPORARY TABLE booking_welcome_voucher_allocations(booking_payment_account_id bigint,amount numeric,state text);
 CREATE TEMPORARY TABLE treatment_credit_entries(booking_payment_account_id bigint,entry_type text,signed_amount numeric);
 CREATE TEMPORARY TABLE gift_voucher_payment_entries(id bigint,order_id bigint,created_at timestamptz,amount numeric,method text);
 CREATE TEMPORARY TABLE gift_vouchers(id bigint,order_id bigint,balance numeric,state text,valid_until date);
 CREATE TEMPORARY TABLE gift_voucher_ledger_entries(id bigint,voucher_id bigint,created_at timestamptz,entry_type text,amount numeric,operation_key text);
 INSERT INTO client_package_entitlements VALUES(1,'2026-10-05 11:30Z',1400,'card_machine','paid'),(2,'2026-10-05 11:30Z',1400,'cash','pending'),(3,'2026-10-05 11:30Z',1400,null,'paid');
 INSERT INTO appointments VALUES(1,'2026-10-05 10:00Z','completed',590,'Massage'),(2,'2026-10-05 12:00Z','completed',700,'Visit 2'),(3,'2026-10-10 10:00Z','scheduled',800,'Visit 3'),(4,'2026-10-05 14:00Z','completed',null,'Missing price'),(5,'2026-10-05 16:00Z','cancelled',1000,'Cancelled');
 INSERT INTO appointment_services VALUES(1,1,'Massage'),(1,2,'Facial');
 INSERT INTO appointment_groups VALUES(10,1500,1600);
 INSERT INTO appointment_group_members VALUES(10,2,700),(10,3,800);
 INSERT INTO booking_payment_accounts VALUES(11,1,null,590),(12,null,10,1500);
 INSERT INTO payment_ledger_entries VALUES(1,11,'2026-10-05 08:00Z','payment',300,'cash'),(2,11,'2026-10-05 09:00Z','refund',25,'cash'),(3,12,'2026-10-05 10:00Z','payment',750,'ozow');
 INSERT INTO booking_loyalty_allocations VALUES(11,100,'applied'),(11,50,'reversed');
 INSERT INTO booking_welcome_voucher_allocations VALUES(12,100,'applied');
 INSERT INTO gift_vouchers VALUES(1,100,500,'active',null),(2,101,100,'active','2026-10-04');
 INSERT INTO gift_voucher_payment_entries VALUES(1,100,'2026-10-05 11:00Z',1000,'cash');
 INSERT INTO gift_voucher_ledger_entries VALUES(1,1,'2026-10-05 11:00Z','issue',1000,'issue:walk-in:1'),(2,1,'2026-10-05 12:00Z','redemption',500,'redeem:1'),(3,2,'2026-10-05 13:00Z','issue',100,'issue:ozow:1');
 `);
 const period=resolvePeriod({preset:'today',now:new Date('2026-10-05T15:00Z')});
 const params=[period.from,period.to,period.previousFrom,period.previousTo];
 const treatments=(await db.query(TREATMENTS_SQL,params)).rows;
 const receipts=(await db.query(RECEIPTS_SQL,params)).rows;
 const balances=(await db.query(BALANCES_SQL,params.slice(0,2))).rows;
 const vouchers=(await db.query(VOUCHERS_SQL,[period.from,period.to,'2026-10-05'])).rows;
 const report=summarizeFinancials({period,treatments,receipts,balances});
 assert.equal(report.current.treatmentValue,1290);
 assert.equal(report.current.unpricedCount,1);
 assert.equal(report.current.received,3550);
 assert.equal(report.current.voucherReceipts,1100);
 assert.equal(report.current.netReceived,3525);
 assert.equal(report.outstanding,865);
 assert.equal(report.balanceReviewCount,1);
 assert.equal(report.unpaid.length,2);
 assert.equal(report.unpaid.find(x=>x.groupId).outstanding,650);
 assert.equal(report.unpaid.find(x=>x.groupId).mixedStatus,true);
 assert.equal(Number(vouchers[0].available_balance),500);
 assert.equal(Number(vouchers[0].expired_balance),100);
 assert.equal(Number(vouchers[0].redeemed_value),500);
 assert.equal(Number(vouchers[0].issued_count),2);
 // Noncash application/return changes only collection balances, never receipts or treatment value.
 await db.query("INSERT INTO treatment_credit_entries VALUES(11,'apply',-80),(11,'undo',30)");
 const corrected=summarizeFinancials({period,treatments,receipts,balances:(await db.query(BALANCES_SQL,params.slice(0,2))).rows});
 assert.equal(corrected.outstanding,815);
 assert.equal(corrected.current.treatmentValue,report.current.treatmentValue);
 assert.equal(corrected.current.received,report.current.received);
 assert.equal(corrected.current.netReceived,report.current.netReceived);
 // Recorded credit account price remains evidence even if a later price becomes unknown/changed.
 await db.query("INSERT INTO booking_payment_accounts VALUES(13,4,null,100); INSERT INTO treatment_credit_entries VALUES(13,'apply',-30),(13,'undo',10)");
 const preserved=(await db.query(BALANCES_SQL,params.slice(0,2))).rows.find(row=>Number(row.appointment_id)===4);
 assert.equal(Number(preserved.amount_due),100); assert.equal(Number(preserved.credits),20);
 await db.query("UPDATE appointments SET total_price=120 WHERE id=4");
 assert.equal(Number((await db.query(BALANCES_SQL,params.slice(0,2))).rows.find(row=>Number(row.appointment_id)===4).amount_due),100);
 await db.query("UPDATE appointments SET status='cancelled' WHERE id=1");
 assert.equal((await db.query(BALANCES_SQL,params.slice(0,2))).rows.some(row=>Number(row.appointment_id)===1),false);
 assert.deepEqual((await db.query(RECEIPTS_SQL,params)).rows,receipts);
 console.log('PostgreSQL financial execution proof passed: completed-only prices, combined treatments, linked-account deduplication, mixed-status groups, refunds, applied/reversed credits, unpriced visits, walk-in and verified Ozow voucher receipts without counting redemption as cash; partial treatment-credit return, preserved account price and cancelled collection balances without changing receipts.');
 } finally { await db.query('ROLLBACK'); await db.end(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
